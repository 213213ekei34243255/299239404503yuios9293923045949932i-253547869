"""Bundles Electron Jonah's Noah agent (Noah/**/*.cjs) UNCHANGED into one script that runs in Jonah's side panel.

  python -I bundle_noah.py <electron jonah dir> <output .js>

Each file becomes a module in a registry; require() resolves "./x", "../y/z" (with or without .cjs/.js/.json) and the
Node/Electron built-ins come from noah-builtins.js (window.NoahBuiltins). Files listed in OVERRIDES are replaced by
Jonah-on-Chromium versions (jonah-ext-src/noah/...), e.g. the tab registry, which in Electron read the Electron window's
own tabs and here uses the browser's real tabs. Tests, benchmarks and docs are left out.
"""
import json
import sys
from pathlib import Path

electron, out = Path(sys.argv[1]), Path(sys.argv[2])
noah = electron / "Noah"
SRC = Path(__file__).parent / "jonah-ext-src" / "noah"
SKIP_DIRS = {"bench", "test", "tests", "docs", "node_modules"}
OVERRIDES = {
    "browser/tabs.cjs": SRC / "tabs.cjs",                   # the browser's real tabs (chrome.tabs + chrome.debugger)
    "perception/screenshot.cjs": SRC / "screenshot.cjs",    # async image work (no Electron nativeImage)
}

mods = {}
for p in sorted(noah.rglob("*")):
    rel = p.relative_to(noah).as_posix()
    if p.is_dir() or set(p.relative_to(noah).parts[:-1]) & SKIP_DIRS:
        continue
    if p.suffix in (".cjs", ".js", ".json"):
        mods[rel] = p
for rel, p in OVERRIDES.items():
    mods[rel] = p

parts = ["""// noah-bundle.js - GENERATED by scripts/bundle_noah.py from Electron Jonah's Noah/ folder (files unchanged except the
// overrides listed in that script). Do not edit by hand.
(function () {
  "use strict";
  const defs = Object.create(null), cache = Object.create(null);
  const B = window.NoahBuiltins;
  function norm(p) { const out = []; for (const s of p.split("/")) { if (!s || s === ".") continue; if (s === "..") out.pop(); else out.push(s); } return out.join("/"); }
  function resolve(from, req) {
    if (!req.startsWith(".")) return { builtin: req };
    const dir = from.includes("/") ? from.slice(0, from.lastIndexOf("/")) : "";
    const base = norm((dir ? dir + "/" : "") + req);
    for (const c of [base, base + ".cjs", base + ".js", base + ".json", base + "/index.cjs", base + "/index.js"]) if (defs[c]) return { id: c };
    throw new Error("Noah: cannot find module '" + req + "' from " + from);
  }
  function load(id) {
    if (cache[id]) return cache[id].exports;
    const module = { exports: {}, id };
    cache[id] = module;
    const req = (r) => {
      const x = resolve(id, r);
      if (x.builtin) return B.modules[x.builtin] || B.stub(x.builtin);
      return load(x.id);
    };
    const dir = "/noah/" + (id.includes("/") ? id.slice(0, id.lastIndexOf("/")) : "");
    defs[id].call(module.exports, module, module.exports, req, "/noah/" + id, dir);
    return module.exports;
  }
"""]
for rel, p in mods.items():
    text = p.read_text(encoding="utf-8")
    if p.suffix == ".json":
        body = "module.exports = " + json.dumps(json.loads(text)) + ";"
    else:
        body = text.replace("\r\n", "\n")
        if body.startswith("#!"):
            body = "//" + body
    parts.append(f"  defs[{json.dumps(rel)}] = function (module, exports, require, __filename, __dirname) {{\n{body}\n}};\n")
parts.append("""  window.NoahRequire = (id) => load(norm(id));
  window.NoahModules = () => Object.keys(defs);
})();
""")
out.write_text("".join(parts), encoding="utf-8", newline="\n")
print(f"bundled {len(mods)} Noah files into {out} ({out.stat().st_size // 1024} KB)")
